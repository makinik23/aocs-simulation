function annotateNadirController(model)
%ANNOTATENADIRCONTROLLER Add editable mathematical notes to the quaternion PD.
% Only annotations tagged NadirMath:* are replaced. Blocks/wires are untouched.
% Equations use native rich-text <math> objects and remain editable in Simulink.
% Call explicitly, then save the model. This function is not a model callback.
arguments
    model (1,1) string = "aocs_plant"
end
p = model + "/GNC/PD feedback linearisation";
c = p + "/Controller";
e = p + "/Error Calculation";
for sys = [p c e]
    handles = find_system(char(sys),'FindAll','on','SearchDepth',1,'Type','annotation');
    for h = handles(:)'
        note = get_param(h,'Object');
        if startsWith(string(note.Tag),'NadirMath:'), delete(note); end
    end
end

% Outer loop: short operating contract above the existing diagram.
card(p,'overview',[85 -235 1180 -45], ...
    'PD kwaternionowy z kompensacją dynamiki — kontrakt regulatora', ...
    {'I: układ inercjalny; D: zadany LVLH; B: korpus. Daszek oznacza estymatę MEKF.', ...
     'Regulator otrzymuje estymatę i referencję. Prawda symulacyjna nie jest wejściem sterowania.', ...
     'Error Calculation: błędy i transformacje. Controller: moment żądany. Poniżej: ograniczenie i bramka jakości.'}, ...
    {'q_e=[q_0;\,q_v],\quad e_\omega=\hat\omega_{BI}^{B}-C_{BD}\omega_{DI}^{D},\quad q_0\geq0'});
card(p,'execution',[85 495 1180 770], ...
    'Wykonanie dyskretne, nasycenie i dopuszczenie sterowania', ...
    {'GNC wywołuje kolejno: odczyt czujników → TRIAD → MEKF → regulator.', ...
     'g = Controller Enabled AND AttitudeHealth.control_usable AND ReferenceVectors.valid.', ...
     'Nasycenie jest osobne dla każdej osi. Między wywołaniami moment jest podtrzymywany (ZOH).', ...
     'Ts = AOCS.GNC.SampleTime_s; limit = AOCS.Control.MaxTorque_Nm. Scenariusz nadir: 0,1 s i 20 µNm/oś.', ...
     'Jest to idealny moment w korpusie; brak alokacji i dynamiki kół. Dowód wewnątrz Controller dotyczy modelu idealnego.'}, ...
    {'\tau_B[k]=\begin{cases}\mathrm{sat}_{[-\tau_{\max},\tau_{\max}]}(\tau_{\mathrm{dem}}[k]),&g[k]=1\\0,&g[k]=0\end{cases}', ...
     '\tau_B(t)=\tau_B[k],\qquad kT_s\leq t<(k+1)T_s'});

% Error calculation: convention must match Aerospace quaternion blocks.
card(e,'frames',[60 -260 1170 -45], ...
    'Konwencje: kwaternion scalar-first i transformacja D → B', ...
    {'C_AB przelicza współrzędne z układu B do A. Kwaterniony są jednostkowe; iloczyn Hamiltona jak w quatmultiply.', ...
     'W obliczeniach C_BI pochodzi z MEKF. Symbol C_BD poniżej oznacza jego estymatę.', ...
     'Kolejność mnożenia kwaternionów jest istotna dla pasywnej konwencji Aerospace.'}, ...
    {'C_{BD}=C(\hat q_{BI})C(q_{DI})^T,\qquad q_e^{\mathrm{raw}}=q_{DI}^{*}\otimes\hat q_{BI}', ...
     'q_e=\begin{cases}q_e^{\mathrm{raw}},&q_{e,0}^{\mathrm{raw}}\geq0\\-q_e^{\mathrm{raw}},&q_{e,0}^{\mathrm{raw}}<0\end{cases}'});
card(e,'errors',[60 360 1170 590], ...
    'Co dokładnie oznaczają wyjścia błędu?', ...
    {'Obie prędkości odejmujemy w osiach B. Samo odjęcie składowych z B i D byłoby błędem.', ...
     'Zmiana znaku dotyczy całego kwaternionu: q i −q opisują tę samą orientację.', ...
     'Wybór q0 ≥ 0 usuwa niepotrzebny pełny obrót (unwinding), lecz przy 180° gałąź jest nieciągła.', ...
     'W Controller sygnał attitude_error = 2 qv. Przy dużym kącie nie jest równy wektorowi kąta w radianach.'}, ...
    {'r=C_{BD}\omega_{DI}^{D},\quad e_\omega=\hat\omega_{BI}^{B}-r\quad[\mathrm{rad/s}]', ...
     'q_v=n\sin(\theta/2),\qquad 2q_v=2n\sin(\theta/2)\simeq n\theta\quad (\theta\simeq0)'});

% Controller: equations above, derivation and proof below. Preserve block layout.
card(c,'law',[60 -310 1260 -40], ...
    'Prawo sterowania realizowane przez bloczki', ...
    {'q_e = [q0; qv], e = e_omega, omega-hat = estymowana prędkość BI w osiach B; J = AOCS.Spacecraft.I_B.', ...
     'kp = AOCS.Control.Kp_s2 > 0 [s⁻²]; kd = AOCS.Control.Kd_s > 0 [s⁻¹]. Wzmocnienia są skalarne, jednakowe na osiach.', ...
     'Proportional Acc + Rate Damping → u. Reference Rate/Acceleration in Body → r, a.', ...
     'Transport Term → e × r; Inertia Times Acceleration → J(...); Gyroscopic Compensation → omega-hat × (J omega-hat).'}, ...
    {'u=-2k_pq_v-k_de,\qquad r=C_{BD}\omega_{DI}^{D},\qquad a=C_{BD}\alpha_{DI}^{D}', ...
     '\tau_{\mathrm{dem}}=\hat\omega\times(J\hat\omega)+J\left(u-e\times r+a\right)'});

card(c,'transport',[60 700 660 1080], ...
    '1. Skąd bierze się kompensacja?', ...
    {'Założenia tej części: dokładna estymacja i stała, znana J = Jᵀ > 0.', ...
     'omega = omega_BI^B, omega_r = omega_DI^D, alpha_r = d(omega_DI^D)/dt.', ...
     'Alpha jest pochodną składowych w D. Obrót do B wnosi dodatkowy człon transportowy.', ...
     'Dla tau = tau_dem i tau_d = 0 otrzymujemy dot(e) = u.', ...
     'Kompensujemy dynamikę prędkości; kinematyka kwaternionu nadal jest nieliniowa.'}, ...
    {'J\dot\omega+\omega\times(J\omega)=\tau+\tau_d', ...
     '\dot C_{BD}=-[e]_\times C_{BD},\qquad [e]_\times r=e\times r', ...
     '\dot r=-e\times r+a,\qquad \dot e=\dot\omega+e\times r-a', ...
     '\dot e=-2k_pq_v-k_de+J^{-1}\tau_d'});
card(c,'lyapunov',[715 700 1330 1080], ...
    '2. Funkcja Lapunowa — idealny model ciągły', ...
    {'Założenia: tau_d = 0, brak nasycenia, sterowanie aktywne, dokładna estymacja i J.', ...
     'Referencje q_r, omega_r, alpha_r są spójne kinematycznie; sterowanie działa w czasie ciągłym.', ...
     'Na gałęzi q0 > 0 funkcja V jest dodatnia poza równowagą q0 = 1, qv = 0, e = 0.', ...
     'V ma jednostkę s⁻²; nie jest fizyczną energią obrotową. Pochodna jest ujemnie półokreślona.'}, ...
    {'\dot q_0=-\frac12q_v^Te,\qquad \dot q_v=\frac12(q_0I+[q_v]_\times)e', ...
     'V=4k_p(1-q_0)+\frac12e^Te', ...
     '\dot V=-4k_p\dot q_0+e^T\dot e', ...
     '\dot V=2k_pq_v^Te+e^T(-2k_pq_v-k_de)', ...
     '\dot V=-k_d\|e\|^2\leq0'});
card(c,'stability',[60 1140 660 1480], ...
    '3. Co z tego wynika? Zbieżność z zasady LaSalle’a', ...
    {'Rozpatrujemy zwarte podpoziomy V ≤ c < 4 kp na sferze jednostkowych kwaternionów.', ...
     'Wtedy q0 ≥ 1 − c/(4 kp) > 0: trajektoria pozostaje na gładkiej gałęzi, bez przejścia przez 180°.', ...
     'dot(V) = 0 wymaga e = 0. Aby w tym zbiorze pozostać, potrzebne jest dot(e) = 0, czyli qv = 0.', ...
     'Największy zbiór niezmienniczy to q0 = 1, qv = 0, e = 0. Stąd lokalna asymptotyczna stabilność.', ...
     'Warunek V(0) < 4 kp jest wystarczający dla tego dowodu; nie opisuje całego obszaru przyciągania.', ...
     'Małe kąty dają model drugiego rzędu na każdej osi. Dla kp = 0,0004 i kd = 0,04: omega_n = 0,02 rad/s, zeta = 1.'}, ...
    {'e=0,\quad\dot e=0\ \Longrightarrow\ q_v=0,\ q_0=1', ...
     '\ddot\theta+k_d\dot\theta+k_p\theta\simeq0,\quad\omega_n=\sqrt{k_p},\quad\zeta=\frac{k_d}{2\sqrt{k_p}}'});
card(c,'limits',[715 1140 1330 1480], ...
    '4. Granice dowodu w tej symulacji', ...
    {'Rzeczywista implementacja jest próbkowana, ma ograniczenie momentu i bramkę jakości; korzysta z MEKF.', ...
     'Guidance używa przybliżenia omega_r dla lokalnie płaskiej orbity oraz różnicy wstecznej alpha_r.', ...
     'Dlatego to dowód dla idealizacji regulatora, a nie gwarancja globalnej stabilności pełnego modelu.', ...
     'Przy błędach estymacji, referencji, J, zakłóceniach, nasyceniu lub podtrzymaniu pojawia się reszta d_eff.', ...
     'Wtedy dot(V) nie musi być ujemna w każdej chwili. PD może pozostawić uchyb orientacji.', ...
     'Dla stałej reszty i małych kątów: theta_ss ≈ d_eff/kp. Sterowanie nie ma członu całkującego.'}, ...
    {'\dot e=-2k_pq_v-k_de+d_{\mathrm{eff}}', ...
     '\dot V=-k_d\|e\|^2+e^Td_{\mathrm{eff}}'});
end

function card(sys,tag,position,title,paragraphs,equations)
% Qt rich-text math objects support editable LaTeX equations in R2025a.
body = ['<p style="font-size:17px;font-weight:600;color:#123955;">' escape(title) '</p>'];
for k=1:numel(paragraphs)
    body = [body '<p style="margin-top:5px;margin-bottom:5px;">' escape(paragraphs{k}) '</p>']; %#ok<AGROW>
end
for k=1:numel(equations)
    body = [body '<p style="margin-top:8px;margin-bottom:8px;"><math style="font-size:17px;">$' ...
        escape(equations{k}) '$</math></p>']; %#ok<AGROW>
end
html = ['<html><head><meta name="qrichtext" content="1"/></head>' ...
    '<body style="font-family:Helvetica;font-size:14px;color:#152536;">' body '</body></html>'];
note = Simulink.Annotation(char(sys),html);
note.Interpreter = 'rich';
note.Tag = ['NadirMath:' tag];
note.Description = ['Mathematical controller documentation. Source: annotateNadirController.m / ' tag];
note.BackgroundColor = '[0.96 0.98 1]';
note.ForegroundColor = 'black';
note.InternalMargins = [12 10 12 10];
note.FixedWidth = 'on';
note.FixedHeight = 'off';
note.Position = position;
end

function text = escape(text)
text = strrep(text,'&','&amp;');
text = strrep(text,'<','&lt;');
text = strrep(text,'>','&gt;');
end
