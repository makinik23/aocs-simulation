function [OrbitNavInternalStateBus, OrbitNavMeasurementBus, ...
    OrbitNavigationStateBus, OrbitNavigationHealthBus, ...
    OrbitNavigationConfigBus] = createOrbitNavigationBuses(targetWorkspace)
%CREATEORBITNAVIGATIONBUSES Define navigation buses.
% I denotes GCRF. Units are SI.

if nargin < 1
    targetWorkspace = "base";
end

OrbitNavInternalStateBus = makeBus("Filter state", [ ...
    element("x_hat", [6 1], "double", "", "State estimate"), ...
    element("P", [6 6], "double", "", "Covariance"), ...
    element("epoch_s", 1, "double", "s", "State epoch"), ...
    element("initialized", 1, "boolean", "1", "Initialized"), ...
    element("last_accepted_gnss_time_s", 1, "double", "s", "Last GNSS update time"), ...
    element("last_processed_sequence_id", 1, "uint32", "1", "Last GNSS sequence"), ...
    element("solution_id", 1, "uint32", "1", "Solution ID")]);

OrbitNavMeasurementBus = makeBus("GNSS measurement", [ ...
    element("z_gnss", [6 1], "double", "", "Position and velocity"), ...
    element("measurement_time_s", 1, "double", "s", "Measurement epoch"), ...
    element("sequence_id", 1, "uint32", "1", "Measurement sequence"), ...
    element("valid", 1, "boolean", "1", "Valid")]);

OrbitNavigationStateBus = makeBus("Navigation state", [ ...
    element("position_I_m", [3 1], "double", "m", "Position"), ...
    element("velocity_I_m_s", [3 1], "double", "m/s", "Velocity"), ...
    element("covariance", [6 6], "double", "", "Covariance"), ...
    element("epoch_s", 1, "double", "s", "State epoch"), ...
    element("state_source", 1, "uint8", "1", "State source"), ...
    element("valid", 1, "boolean", "1", "Valid"), ...
    element("solution_id", 1, "uint32", "1", "Solution ID")]);

OrbitNavigationHealthBus = makeBus("Navigation status", [ ...
    element("mode", 1, "uint8", "1", "Mode"), ...
    element("valid", 1, "boolean", "1", "Valid"), ...
    element("gnss_age_s", 1, "double", "s", "GNSS age"), ...
    element("nis", 1, "double", "1", "NIS"), ...
    element("nis_available", 1, "boolean", "1", "NIS available"), ...
    element("algorithm_ready", 1, "boolean", "1", "Algorithm ready"), ...
    element("update_requested", 1, "boolean", "1", "Update requested"), ...
    element("measurement_sequence_id", 1, "uint32", "1", "GNSS sequence"), ...
    element("execution_time_s", 1, "double", "s", "Execution time")]);

OrbitNavigationConfigBus = makeBus("Navigation configuration", [ ...
    element("sample_time_s", 1, "double", "s", "Sample time"), ...
    element("mu_m3_s2", 1, "double", "m^3/s^2", "Gravitational parameter"), ...
    element("earth_radius_m", 1, "double", "m", "Earth radius"), ...
    element("J2", 1, "double", "1", "J2"), ...
    element("pole_I", [3 1], "double", "1", "Earth axis"), ...
    element("acceleration_noise_psd_m2_s3", 1, "double", "m^2/s^3", "Acceleration noise"), ...
    element("gnss_covariance_RTN", [6 6], "double", "", "Covariance"), ...
    element("initial_state", 1, "Bus: OrbitNavInternalStateBus", "", "Initial state")]);

if string(targetWorkspace) == "base"
    assignin("base", "OrbitNavInternalStateBus", OrbitNavInternalStateBus);
    assignin("base", "OrbitNavMeasurementBus", OrbitNavMeasurementBus);
    assignin("base", "OrbitNavigationStateBus", OrbitNavigationStateBus);
    assignin("base", "OrbitNavigationHealthBus", OrbitNavigationHealthBus);
    assignin("base", "OrbitNavigationConfigBus", OrbitNavigationConfigBus);
end
end

function bus = makeBus(description, elements)
bus = Simulink.Bus;
bus.Description = description;
bus.Elements = elements;
end

function item = element(name, dimensions, dataType, unit, description)
item = Simulink.BusElement;
item.Name = name;
item.Dimensions = dimensions;
item.DataType = dataType;
item.Unit = unit;
item.Description = description;
end
