function config = readAttitudeControlConfig(gnc)
% Quaternion PD/PID acceleration gains and ideal body-torque actuator limits.
raw = optionalStructField(gnc, "attitude_control");
config.Enabled = optionalLogicalScalarField(raw, "enabled", ...
    "gnc.attitude_control.enabled", false);
config.UseIntegral = optionalLogicalScalarField(raw, "use_integral", ...
    "gnc.attitude_control.use_integral", false);
config.Kp_s2 = optionalScalarField(raw, "kp_s2", ...
    "gnc.attitude_control.kp_s2", 0.0004, true);
config.Kd_s = optionalScalarField(raw, "kd_s", ...
    "gnc.attitude_control.kd_s", 0.04, true);
% Independent P/D gains for the PID branch; legacy configs keep their values.
config.PIDKp_s2 = optionalScalarField(raw, "pid_kp_s2", ...
    "gnc.attitude_control.pid_kp_s2", config.Kp_s2, true);
config.PIDKd_s = optionalScalarField(raw, "pid_kd_s", ...
    "gnc.attitude_control.pid_kd_s", config.Kd_s, true);
config.Ki_s3 = optionalScalarField(raw, "ki_s3", ...
    "gnc.attitude_control.ki_s3", 2e-6, true);
config.AntiWindupTime_s = optionalScalarField(raw, "anti_windup_time_s", ...
    "gnc.attitude_control.anti_windup_time_s", 10, true);
config.MaxTorque_Nm = optionalScalarField(raw, "max_torque_Nm", ...
    "gnc.attitude_control.max_torque_Nm", 2e-5, true);
end
